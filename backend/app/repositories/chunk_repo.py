"""``chunks`` table access: per-document replace (ingestion), count, and hybrid search (RRF in SQL).

Hybrid search = one round trip: keyword candidates (``websearch_to_tsquery`` + ``ts_rank_cd`` over the
GIN-indexed ``tsv``) and vector candidates (cosine ``<=>`` over the HNSW index) are fused with Reciprocal
Rank Fusion: ``score = 1/(rrf_k + kw_rank) + 1/(rrf_k + vec_rank)``. Without an embedding (null embedder)
the vector CTE is left out entirely and the search is keyword-only.
"""

from __future__ import annotations

import json
from typing import Any, Final

from pgvector.sqlalchemy import Vector
from sqlalchemy import bindparam, delete, func, insert, select, text

from app.core.constants import EMBED_DIM, HYBRID_CANDIDATES, RRF_K
from app.models.chunk import Chunk
from app.repositories.base import SqlRepository

_KW_CTE: Final = """
kw AS (
  SELECT c.id, row_number() OVER (ORDER BY ts_rank_cd(c.tsv, q.tsq) DESC, c.id) AS r
  FROM chunks c, q
  WHERE c.tsv @@ q.tsq AND c.metadata @> CAST(:filter AS jsonb)
  ORDER BY r LIMIT :k)"""

_VEC_CTE: Final = """
vec AS (
  SELECT c.id, row_number() OVER (ORDER BY c.embedding <=> :emb, c.id) AS r
  FROM chunks c
  WHERE c.embedding IS NOT NULL AND c.metadata @> CAST(:filter AS jsonb)
  ORDER BY c.embedding <=> :emb LIMIT :k)"""

_HYBRID_SQL: Final = f"""
WITH q AS (SELECT websearch_to_tsquery('english', :query) AS tsq),{_KW_CTE},{_VEC_CTE}
SELECT c.id, c.doc_id, c.page, c.section, c.text, c.metadata,
       COALESCE(1.0 / (:rrf_k + kw.r), 0) + COALESCE(1.0 / (:rrf_k + vec.r), 0) AS score
FROM chunks c
LEFT JOIN kw  ON kw.id  = c.id
LEFT JOIN vec ON vec.id = c.id
WHERE kw.id IS NOT NULL OR vec.id IS NOT NULL
ORDER BY score DESC, c.id
LIMIT :top_n"""

_KEYWORD_SQL: Final = f"""
WITH q AS (SELECT websearch_to_tsquery('english', :query) AS tsq),{_KW_CTE}
SELECT c.id, c.doc_id, c.page, c.section, c.text, c.metadata,
       1.0 / (:rrf_k + kw.r) AS score
FROM chunks c
JOIN kw ON kw.id = c.id
ORDER BY score DESC, c.id
LIMIT :top_n"""

HYBRID_QUERY = text(_HYBRID_SQL).bindparams(bindparam("emb", type_=Vector(EMBED_DIM)))
KEYWORD_QUERY = text(_KEYWORD_SQL)


class PgChunkRepository(SqlRepository[Chunk]):
    model = Chunk
    conflict_cols = ("id",)

    async def replace_for_doc(self, doc_id: str, chunks: list[dict[str, Any]]) -> int:
        """Delete every chunk of ``doc_id``, then insert ``chunks``.

        ``chunks`` are dicts keyed by column name (``doc_id, page, section, text, metadata, embedding``);
        ``id`` and ``tsv`` are generated by Postgres. Does not commit.
        """
        await self.session.execute(delete(Chunk).where(Chunk.doc_id == doc_id))
        if chunks:
            # table-level insert: keys are column names ("metadata"), not ORM attributes ("metadata_")
            await self.session.execute(insert(self.table), chunks)
        return len(chunks)

    async def count(self) -> int:
        return int(await self.session.scalar(select(func.count()).select_from(self.table)) or 0)

    async def hybrid_search(
        self,
        query: str,
        embedding: list[float] | None,
        top_n: int = 5,
        filter: dict[str, Any] | None = None,
        *,
        k: int = HYBRID_CANDIDATES,
        rrf_k: int = RRF_K,
    ) -> list[dict[str, Any]]:
        """Top ``top_n`` chunks by RRF over keyword + vector candidates (``k`` each), optionally restricted to
        chunks whose ``metadata`` contains ``filter`` (JSONB ``@>``)."""
        params: dict[str, Any] = {
            "query": query,
            "filter": json.dumps(filter or {}),
            "k": k,
            "rrf_k": rrf_k,
            "top_n": top_n,
        }
        if embedding is not None:
            stmt, params["emb"] = HYBRID_QUERY, embedding
        else:
            stmt = KEYWORD_QUERY
        result = await self.session.execute(stmt, params)
        return [{**row, "score": float(row["score"])} for row in result.mappings()]


__all__ = ["PgChunkRepository"]
